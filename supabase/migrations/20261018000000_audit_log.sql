-- Audit log table.
-- Append-only record of sensitive actions: role changes, overrides, placements,
-- record releases, link creations, deletions, school-admin message access.
-- Follows docs/SCHEMA.md section 7 and docs/RLS_RULES.md section 6.
--
-- No update or delete policy exists for any role (including platform admin).
-- RLS is enabled but policies are restrictive: only school admin can read
-- their organisation's rows; platform admin can read all.

create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  organization_id uuid references organizations(id),
  actor_id uuid references profiles(id),
  action text not null,
  table_name text,
  record_id uuid,
  details jsonb,
  created_at timestamptz not null default now()
);

alter table audit_log enable row level security;

-- Indexes for common query patterns
create index idx_audit_log_organization_id on audit_log(organization_id);
create index idx_audit_log_actor_id on audit_log(actor_id);
create index idx_audit_log_created_at on audit_log(created_at);
create index idx_audit_log_table_record on audit_log(table_name, record_id);

-- Policies
-- School admin can read their organisation's audit rows
create policy "audit_log_select_school_admin" on public.audit_log
for select to authenticated
using (
  organization_id = (select private.current_org_id())
  and private.has_role('school_admin')
);

-- Platform admin can read all audit rows
create policy "audit_log_select_platform_admin" on public.audit_log
for select to authenticated
using (
  private.has_role('platform_admin')
);

-- No insert/update/delete policies — writes go through trusted functions only.
-- The anon role has no access.

revoke all on public.audit_log from anon;
revoke all on public.audit_log from authenticated;

-- Trusted function to write audit log entries. Called by server actions
-- for sensitive operations (role changes, overrides, placements, etc.).
create function private.write_audit_log(
  p_organization_id uuid,
  p_actor_id uuid,
  p_action text,
  p_table_name text,
  p_record_id uuid,
  p_details jsonb
)
returns void
language plpgsql
stable
security definer
set search_path = private, public, pg_catalog
as $$
begin
  insert into public.audit_log (
    organization_id,
    actor_id,
    action,
    table_name,
    record_id,
    details,
    created_at
  ) values (
    p_organization_id,
    p_actor_id,
    p_action,
    p_table_name,
    p_record_id,
    p_details,
    now()
  );
end;
$$;

-- Grant execute to authenticated so server actions can call it
grant execute on function private.write_audit_log(
  uuid, uuid, text, text, uuid, jsonb
) to authenticated;

